    /// end today. The emitter is still the place where the cast would be lost, and
    /// `cast_constructor` is the shared logic the compute backend uses, so the unit
    /// here pins it without depending on that refusal being lifted.
    ///
    /// That refusal is a real, separate gap and is recorded rather than hidden: with
    /// it in place, a `as T` cast reaches WGSL only through the compute backend.
    #[test]
    fn cast_constructor_maps_the_supported_scalars() {
        use crate::ast::Span;
        use crate::ast::ty::{Type, TypeKind};
        let mk = |k| Type::new(k, crate::ast::Quantity::Many, Span::default());

        assert_eq!(
            cast_constructor(&mk(TypeKind::Float)).as_deref(),
            Some("f32")
        );
        assert_eq!(cast_constructor(&mk(TypeKind::Int)).as_deref(), Some("i32"));
        assert_eq!(
            cast_constructor(&mk(TypeKind::UInt)).as_deref(),
            Some("u32")
        );
        assert_eq!(
            cast_constructor(&mk(TypeKind::Bool)).as_deref(),
            Some("bool")
        );
        // A tensor ascription carries no conversion, so the inner expression stands.
        assert_eq!(cast_constructor(&mk(TypeKind::Tensor(vec![]))), None);

        // Width lives in `int_width`, not in the TypeKind. Emitting `i32(x)` for an
        // `i8` would silently widen it -- the same wrong-answer bug as binding an i8
        // tensor as `array<i32>` -- so a narrow cast has no WGSL spelling here.
        let mut narrow = mk(TypeKind::Int);
        narrow.int_width = Some(8);
        assert_eq!(
            cast_constructor(&narrow),
            None,
            "widening i8 to i32 is the silent-wrong-answer bug"
        );
    }

    /// A numeric cast now reaches the straight-line WGSL backend, and survives emission.
    ///
    /// This test was a SENTINEL: while `lower_program` refused `Ascribe`, it asserted
    /// that refusal still held, so that lifting it would be a deliberate act. Lowering
    /// now lowers `e as T` to `PirExpr::Cast`, so the sentinel fired -- and did its job
    /// by naming the rewrite. This is that rewrite.
    ///
    /// The bug it guards: `ExprKind::Ascribe` was emitted as its INNER EXPRESSION, so
    /// `clamp(v) as i32` became `clamp(v)`. The shader still PARSED, so a parse-only
    /// check accepted it, and a driver would reject it -- an f32 stored into an
    /// `array<i32>`.
    #[test]
    fn a_numeric_cast_survives_emission_to_the_straight_line_backend() {
        let src = "fn clamp_i32(v: f32) -> i32 { return clamp(v, -128.0, 127.0) as i32; }";
        let program = parse_program(src).expect("parse");

        // The refusal is gone.
        assert!(
            crate::lowering::lower_program(&program).is_ok(),
            "a cast must lower; this test exists to assert that it reaches codegen"
        );

        let w = generate_wgsl_straight_line(&program).expect("shader");
        // The emitter parenthesises every subexpression, so match on the
        // constructor plus the call inside it rather than the whole expression.
        assert!(
            w.contains("i32(clamp("),
            "the cast must appear as an i32(...) constructor, not vanish:\n{w}"
        );
        assert!(
            !w.contains("return clamp("),
            "returning the inner expression would mean the cast was dropped:\n{w}"
        );
    }
